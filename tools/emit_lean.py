"""Emit certificate data as Lean source (plain literals), checked in the kernel.

    python3 tools/emit_lean.py iso D [CHUNK]

iso: every class-merge isometry (data/cand_classes_D.json): for each non-representative
member L with certificate phi, a theorem
    checkIso G_member G_rep phi = true        (by decide +kernel)
i.e. phi^T G_rep phi = G_member with phi in GL_3(O). Files:
lean/ReflectZphi/Data/Iso<D>_<k>.lean, CHUNK certificates each, plus an index module
lean/ReflectZphi/Data/Iso<D>.lean importing them.

The generator is trusted only not to omit data: every emitted claim is re-checked by
the kernel (lean-plan.md section 4).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from zphi.fields import PROFILES, OUTPUT_NAMES  # noqa: E402

OUT = os.path.join(ROOT, "lean", "ReflectZphi", "Data")


def el(x):
    a, b = (list(x) + [0, 0])[:2] if isinstance(x, list) else (x, 0)
    if isinstance(x, list) and len(x) == 3 and x[2] != 1:
        raise ValueError(f"non-integral entry {x}")
    return f"⟨{a}, {b}⟩"


def mat(M):
    return "⟨" + ", ".join(el(M[i][j]) for i in range(3) for j in range(3)) + "⟩"


def norm_label(lab):
    k, key, li = lab.split("|")
    return f"{k}|{json.dumps(json.loads(key))}|{li}"


def emit_iso(D, chunk):
    P = PROFILES[D]
    cl = json.load(open(os.path.join(ROOT, "data", f"cand_classes_{D}.json")))
    data = json.load(open(os.path.join(ROOT, "data", OUTPUT_NAMES[D])))
    grams = {f"{c['kind']}|{json.dumps(c['key'])}|{c['li']}": c["gram"]
             for c in data["candidates"]}
    certs = sorted(cl["certs"].items())
    os.makedirs(OUT, exist_ok=True)
    mods = []
    for k in range(0, len(certs), chunk):
        name = f"Iso{D}_{k // chunk:03d}"
        lines = ["import ReflectZphi.Cert.Iso", "",
                 f"/-! Generated by tools/emit_lean.py from data/cand_classes_{D}.json. "
                 "Do not edit. -/", "",
                 "namespace ReflectZphi.Data", "",
                 f"abbrev O{D} := QuadraticAlgebra ℤ {P.c0} {P.c1}", ""]
        for i, (lab, c) in enumerate(certs[k:k + chunk], start=k):
            if lab.startswith("mark|") or c["rep"].startswith("mark|"):
                continue
            Gm, Gr = grams[norm_label(lab)], grams[norm_label(c["rep"])]
            lines += [f"-- {lab}  ≅  {c['rep']}",
                      f"theorem iso{D}_{i:05d} : checkIso (a := {P.c0}) (b := {P.c1})",
                      f"    ({mat(Gm)} : Mat3 O{D})",
                      f"    ({mat(Gr)} : Mat3 O{D})",
                      f"    ({mat(c['phi'])} : Mat3 O{D}) = true := by",
                      "  decide +kernel", ""]
        lines += ["end ReflectZphi.Data", ""]
        open(os.path.join(OUT, name + ".lean"), "w").write("\n".join(lines))
        mods.append(name)
    idx = [f"import ReflectZphi.Data.{m}" for m in mods]
    open(os.path.join(OUT, f"Iso{D}.lean"), "w").write("\n".join(idx) + "\n")
    print(f"{len(certs)} isometry certificates in {len(mods)} files")


if __name__ == "__main__":
    mode, D = sys.argv[1], int(sys.argv[2])
    chunk = int(sys.argv[3]) if len(sys.argv) > 3 else 50
    {"iso": emit_iso}[mode](D, chunk)
