"""Appendix lists of the manuscript (LaTeX longtables), from the exported class data.

  sections/z-list.tex     the 144 classes over Z[phi]     (data/zphi_rank3.json)
  sections/z-list-2.tex   the 2 new classes over Z[sqrt2] (data/zsqrt2_rank3.json, the
                          classes matching no entry of Mark's appendix), with simple roots
  sections/z-list-13.tex  the 39 classes over Z[omega] and the undecided candidates
                          (data/zsqrt13_rank3.json)

For each class: the cyclic angle sequence pi/m_i, the cyclic sequence of root norms
r_i^2 (canonical totally positive representative modulo unit squares, zphi.ring.tp_normalise;
with the determinant ideal this is the chamber invariant iota of the paper), and the
determinant and Gram matrix of the member with the smallest Gram matrix (sum of |coefficients|).
Classes are ordered by number of sides, then by that size; for Z[phi] this is the numbering
# used throughout the paper (as in the earlier tools/appendix_table.py).

Usage: .venv/bin/python tools/appendix_lists.py
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from zphi.ring import get_ring, from_json, tp_normalise  # noqa: E402
from zphi.linalg import bil  # noqa: E402

PAPER = ROOT.parent / "reflect-zphi-paper/sections"
SYM = {5: r"\varphi", 2: r"\sqrt2", 13: r"\omega"}


def el(x, D):
    a, b = x[0], x[1]
    den = x[2] if len(x) > 2 else 1
    g = SYM[D]
    if b == 0:
        s = str(a)
    else:
        bs = {1: g, -1: f"-{g}"}.get(b, f"{b}{g}")
        s = bs if a == 0 else f"{a}{'+' if b > 0 else ''}{bs}"
    return s if den == 1 else rf"\tfrac{{{s}}}{{{den}}}"


def height(g):
    return sum(abs(c) for row in g for x in row for c in x[:2])


def gram_tex(g, D):
    return (r"\begin{psmallmatrix}" + r"\\".join("&".join(el(x, D) for x in row) for row in g)
            + r"\end{psmallmatrix}")


def vec_tex(v, D):
    return "(" + ", ".join(el(x, D) for x in v) + ")"


def norms(R, cl):
    G = [[from_json(R, x) for x in row] for row in cl["gram"]]
    out = []
    for v in cl["polygon"]["roots"]:
        r = [from_json(R, x) for x in v]
        out.append(tp_normalise(bil(G, r, r)).to_json())
    return out


def rows(D):
    R = get_ring(D)
    d = json.load(open(ROOT / "data" / {5: "zphi_rank3.json", 2: "zsqrt2_rank3.json",
                                        13: "zsqrt13_rank3.json"}[D]))
    cands = {f"{c['kind']}|{json.dumps(c['key'])}|{c['li']}": c for c in d["candidates"]}

    def lookup(label):
        k, key, li = label.split("|")
        return cands[f"{k}|{json.dumps(json.loads(key))}|{li}"]
    out = []
    for cl in d["classes"]:
        labels = [cl["representative"]] + [m["label"] for m in cl["members"]]
        best = min((lookup(l) for l in labels), key=lambda c: height(c["gram"]))
        out.append(dict(sides=cl["sides"], h=height(best["gram"]), cl=cl, best=best,
                        norms=norms(R, cl), new=not cl["mark_classes"]))
    out.sort(key=lambda r: (r["sides"], r["h"]))
    return d, out


HEAD = ("\\begin{longtable}{r>{\\raggedright\\arraybackslash}p{4.2cm}ll}\n\\toprule\n"
        "\\# & angles $\\pi/m_i$; norms $r_i^2$ & $\\det$ & Gram matrix\\\\\n\\midrule\\endhead\n")


def line(i, r, D):
    ang = ",\\allowbreak ".join(str(a) for a in r["cl"]["polygon"]["angles"])
    nm = ",\\allowbreak ".join(f"${el(x, D)}$" for x in r["norms"])
    return (f"{i} & ({ang});\\allowbreak\\ ({nm}) & ${el(r['best']['det'], D)}$ & "
            f"${gram_tex(r['best']['gram'], D)}$\\\\[2pt]\n")


def main():
    # Z[phi]
    _, rs = rows(5)
    with open(PAPER / "z-list.tex", "w") as f:
        f.write("% Generated by reflect-zphi/tools/appendix_lists.py from data/zphi_rank3.json. Do not edit.\n")
        f.write(HEAD)
        for i, r in enumerate(rs, 1):
            f.write(line(i, r, 5))
        f.write("\\bottomrule\n\\end{longtable}\n")
    print(len(rs), "Z[phi] classes")
    # Z[sqrt2]: the classes not matching Mark's appendix
    _, rs = rows(2)
    new = [r for r in rs if r["new"]]
    with open(PAPER / "z-list-2.tex", "w") as f:
        f.write("% Generated by reflect-zphi/tools/appendix_lists.py from data/zsqrt2_rank3.json. Do not edit.\n")
        for r in new:
            cl = r["cl"]
            f.write("\\begin{itemize}\n\\item angles $(" + ",".join(str(a) for a in cl["polygon"]["angles"])
                    + ")$, root norms $(" + ", ".join(el(x, 2) for x in r["norms"]) + ")$, $\\det="
                    + el(cl["det"], 2) + "$,\n\\[G=" + gram_tex(cl["gram"], 2).replace("psmallmatrix", "pmatrix")
                    + ",\\]\nsimple roots (in cyclic order) "
                    + ", ".join("$" + vec_tex(v, 2) + "$" for v in cl["polygon"]["roots"]) + ".\n\\end{itemize}\n")
    print(len(new), "new Z[sqrt2] classes")
    # Z[omega]
    d, rs = rows(13)
    und = [c for c in d["candidates"] if c["status"] not in ("reflective", "nonreflective")]
    with open(PAPER / "z-list-13.tex", "w") as f:
        f.write("% Generated by reflect-zphi/tools/appendix_lists.py from data/zsqrt13_rank3.json. Do not edit.\n")
        f.write(HEAD)
        for i, r in enumerate(rs, 1):
            f.write(line(i, r, 13))
        f.write("\\bottomrule\n\\end{longtable}\n")
        f.write("The undecided candidates:\n\\begin{itemize}\n")
        for c in und:
            kind = {"short_edge": "short edge", "short_pair": "short pair", "close_pair": "close pair"}[c["kind"]]
            f.write(f"\\item from a {kind} configuration: $\\det={el(c['det'], 13)}$,\n"
                    f"\\[G={gram_tex(c['gram'], 13).replace('psmallmatrix', 'pmatrix')}.\\]\n")
        f.write("\\end{itemize}\n")
    print(len(rs), "Z[omega] classes,", len(und), "undecided")


if __name__ == "__main__":
    main()
