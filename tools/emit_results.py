"""Emit lean/ReflectZphi/Results.lean: the headline theorems of the Lean development over Z[phi].

The file states, in the numbering of the paper (Appendix A.3, as tools/appendix_lists.py
orders the classes),

  all_reflective (hV : VinbergChamber) (n : Fin 144) : Reflective hd5 (classGram n)

where classGram n is the Gram matrix G of the certificate module of class #(n+1), i.e. of
the class representative in data/zphi_rank3.json. Where Appendix A.3 prints a different
(isometric) member, the comment of the entry names the isometry certificate in
ReflectZphi.Data.Iso5_* that links the printed member to G. It also runs
`#audit_axioms ReflectZphi.Data` (every certificate and isometry theorem) and
`#print axioms all_reflective`.

Building it rebuilds every certificate module (about 25 CPU-hours of kernel checks).

Usage: .venv/bin/python tools/emit_results.py
"""
from __future__ import annotations

import glob
import json
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
import appendix_lists  # noqa: E402

OUT = ROOT / "lean/ReflectZphi/Results.lean"


def label(c):
    return f"{c['kind']}|{json.dumps(c['key'])}|{c['li']}"


def norm_label(s):
    k, key, li = s.split("|")
    return f"{k}|{json.dumps(json.loads(key))}|{li}"


def iso_theorems():
    """(label, label) -> Lean name of the checkIso theorem, both orientations."""
    out = {}
    for f in sorted(glob.glob(str(ROOT / "lean/ReflectZphi/Data/Iso5_*.lean"))):
        mod = os.path.basename(f)[:-5]
        txt = open(f).read()
        for a, b, thm in re.findall(r"^-- (.*?)  ≅  (.*)\n(?:.*\n)*?theorem (\w+) :", txt, re.M):
            a, b = norm_label(a.strip()), norm_label(b.strip())
            out[(a, b)] = out[(b, a)] = f"ReflectZphi.Data.{mod}.{thm}"
    return out


def main():
    d, rows = appendix_lists.rows(5)
    index = {id(c): i for i, c in enumerate(d["classes"])}
    isos = iso_theorems()
    entries = []
    for n, r in enumerate(rows, 1):
        i = index[id(r["cl"])]
        rep = norm_label(r["cl"]["representative"])
        best = label(r["best"])
        ang = ",".join(str(a) for a in r["cl"]["polygon"]["angles"])
        if best == rep:
            note = "printed matrix = G"
        else:
            note = f"printed member ≅ G by {isos[(best, rep)]}"
        entries.append((n, i, ang, note))
    N = len(entries)
    L = [
        "import ReflectZphi.Audit",
        "import ReflectZphi.Data.Cert5",
        "import ReflectZphi.Data.Iso5",
        "",
        "/-!",
        "# Main results over ℤ[φ]",
        "",
        "Generated by `tools/emit_results.py` from `data/zphi_rank3.json`. Do not edit.",
        "",
        "This file is the entry point for checking the formal part of the paper. Compiling it",
        "rebuilds every certificate module, so the Lean kernel re-checks all certificates",
        "(about 25 CPU-hours).",
        "",
        "## What is proved",
        "",
        f"* `all_reflective`: for each of the {N} classes over ℤ[φ] of the paper, numbered as in",
        "  Appendix A.3 (`n : Fin 144` is class `#(n+1)`), the lattice `(𝒪³, classGram n)` is",
        "  reflective, under the imported hypothesis `VinbergChamber` (Appendix A.1). Here",
        "  `classGram n` is the Gram matrix `G` of the class representative, the matrix that",
        "  certificate module `Data.Cert5.C###` is about.",
        "* The isometry certificates `Data.Iso5_*.iso5_*` (one per member of each class) state",
        "  `checkIso G₁ G₂ P = true`; by `checkIso_sound` this means `P ∈ GL₃(𝒪)` and",
        "  `Pᵀ G₂ P = G₁`. For 118 classes Appendix A.3 prints a member other than the",
        "  representative; the comment of each entry below names the certificate linking it to",
        "  `G`. There is no Lean theorem transferring reflectivity along an isometry, so",
        "  `all_reflective` is stated for the representatives.",
        "* `#audit_axioms ReflectZphi.Data` fails unless every theorem of the certificate library",
        "  uses only `propext`, `Classical.choice` and `Quot.sound`; `#print axioms",
        "  all_reflective` shows the same for the headline theorem. The imported results are",
        "  hypotheses, not axioms.",
        "",
        "## What is not proved here",
        "",
        "The completeness of the enumeration (the configurations, the candidate lattices and the",
        "local-simplicity filter), the non-reflectivity certificates and the pairwise",
        "non-isometry of the classes are proved in the paper and checked by the Python code, not in",
        "Lean (paper, Section 15).",
        "-/",
        "",
        "set_option maxRecDepth 8192",
        "",
        "namespace ReflectZphi.Results",
        "",
        "open ReflectZphi ReflectZphi.Lattice",
        "",
        "/-- The coefficient ring ℤ[φ], φ² = φ + 1. -/",
        "abbrev O5 := QuadraticAlgebra ℤ 1 1",
        "",
        "/-- The discriminant condition for ℤ[φ] (`b² + 4a = 5 ≥ 0`). -/",
        "theorem hd5 : (0 : ℝ) ≤ ((1 : ℤ) : ℝ) ^ 2 + 4 * ((1 : ℤ) : ℝ) := by norm_num",
        "",
        "/-- `classGram n`: the Gram matrix of the representative of class `#(n+1)` of",
        "Appendix A.3 (the matrix of its certificate module). -/",
        f"def classGram : Fin {N} → Matrix (Fin 3) (Fin 3) O5 := ![",
    ]
    for k, (n, i, ang, note) in enumerate(entries):
        sep = "," if k < N - 1 else ""
        L.append(f"  Data.Cert5.C{i:03d}.G{sep}  -- #{n}, angles ({ang}); {note}")
    L += [
        "  ]",
        "",
        f"/-- Every one of the {N} classes over ℤ[φ] is reflective (assuming Vinberg's chamber",
        "theorem, `VinbergChamber`). -/",
        f"theorem all_reflective (hV : VinbergChamber) (n : Fin {N}) :",
        "    Reflective hd5 (classGram n) := by",
        "  fin_cases n",
        "  exacts [" + ",\n    ".join(f"Data.Cert5.C{i:03d}.reflective hV" for _, i, _, _ in entries) + "]",
        "",
        "end ReflectZphi.Results",
        "",
        "#print axioms ReflectZphi.Results.all_reflective",
        "#audit_axioms ReflectZphi.Data",
        "#audit_axioms ReflectZphi.Results",
        "",
    ]
    OUT.write_text("\n".join(L))
    print(f"{N} classes -> {OUT}")


if __name__ == "__main__":
    main()
