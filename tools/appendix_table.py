"""Generate the appendix table of the 144 classes over Z[phi] (LaTeX longtable).

For each class, the member with the smallest Gram matrix (sum of |coefficients|) is printed.
Elements [a, b] mean a + b*phi.  Usage: python3 tools/appendix_table.py OUT.tex
"""
import json, sys

def el(x):
    a, b = x
    if b == 0:
        return str(a)
    bs = {1: r"\varphi", -1: r"-\varphi"}.get(b, f"{b}\\varphi")
    if a == 0:
        return bs
    return f"{a}{'+' if b > 0 else ''}{bs}"

def height(g):
    return sum(abs(c) for row in g for x in row for c in x)

def main(out):
    d = json.load(open("data/zphi_rank3.json"))
    cands = {f"{c['kind']}|{json.dumps(c['key'])}|{c['li']}": c for c in d["candidates"]}
    def lookup(label):
        k, key, li = label.split("|")
        return cands[f"{k}|{json.dumps(json.loads(key))}|{li}"]
    rows = []
    for cl in d["classes"]:
        labels = [cl["representative"]] + [m["label"] for m in cl["members"]]
        best = min((lookup(l) for l in labels), key=lambda c: height(c["gram"]))
        g = best["gram"]
        gram = (r"\begin{psmallmatrix}" + r"\\".join(
            "&".join(el(x) for x in row) for row in g) + r"\end{psmallmatrix}")
        ang = ",\\allowbreak ".join(str(a) for a in cl["polygon"]["angles"])
        rows.append((cl["sides"], height(g), ang, el(best["det"]), gram, len(labels)))
    rows.sort(key=lambda r: (r[0], r[1]))
    with open(out, "w") as f:
        f.write("% Generated by reflect-zphi/tools/appendix_table.py from data/zphi_rank3.json. Do not edit.\n")
        f.write("\\begin{longtable}{r>{\\raggedright\\arraybackslash}p{3.6cm}ll}\n\\toprule\n\\# & angles $\\pi/m$ & $\\det$ & Gram matrix\\\\\n\\midrule\\endhead\n")
        for i, (s, _, ang, det, gram, n) in enumerate(rows, 1):
            f.write(f"{i} & ({ang}) & ${det}$ & ${gram}$\\\\[2pt]\n")
        f.write("\\bottomrule\n\\end{longtable}\n")
    print(len(rows), "classes written to", out)

if __name__ == "__main__":
    main(sys.argv[1])
