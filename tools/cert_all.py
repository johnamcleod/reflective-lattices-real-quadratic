"""Emit the reflectivity certificates of all classes of one field into the Lean library.

Writes lean/ReflectZphi/Data/Cert{D}/C###.lean (one module per class, checked in parallel
by `lake build`; each cell's search is cut into subtrees of at most `chunk` nodes, one
declaration each, which keeps the kernel's memory small), the aggregator lean/ReflectZphi/Data/Cert{D}.lean, and
lean/scripts/CertAxioms{D}.lean (`#print axioms` of every `reflective` theorem).
Per-class statistics go to logs/cert_{D}.jsonl. Existing modules are kept unless --force.

Usage: python tools/cert_all.py D [first last] [--cap=N] [--chunk=N] [--maxcell=N] [--force]
       [--split [--budget=NODES]]  (one main module C###.lean + C###/Base.lean + C###/P###.lean)
"""
from __future__ import annotations

import json
import os
import sys
import time

sys.path.insert(0, ".")
from tools.b8_size import FILES  # noqa: E402
from tools import emit_cert  # noqa: E402


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    opts = dict(a[2:].split("=", 1) if "=" in a else (a[2:], "1")
                for a in sys.argv[1:] if a.startswith("--"))
    D = int(args[0])
    ncls = len(json.load(open(FILES[D]))["classes"])
    first = int(args[1]) if len(args) > 1 else 0
    last = int(args[2]) if len(args) > 2 else ncls - 1
    cap = int(opts.get("cap", 3000))
    chunk = int(opts.get("chunk", 300))
    maxcell = int(opts["maxcell"]) if "maxcell" in opts else None
    outdir = f"lean/ReflectZphi/Data/Cert{D}"
    os.makedirs(outdir, exist_ok=True)
    log = open(f"logs/cert_{D}.jsonl", "a")
    for ci in range(first, last + 1):
        path = f"{outdir}/C{ci:03d}.lean"
        if os.path.exists(path) and "force" not in opts:
            continue
        t0 = time.time()
        try:
            C = emit_cert.build(D, ci, cap, maxcell)
        except Exception as e:  # recorded, not hidden
            rec = dict(cls=ci, error=repr(e))
            print(json.dumps(rec), flush=True)
            log.write(json.dumps(rec) + "\n"); log.flush()
            continue
        ns = f"ReflectZphi.Data.Cert{D}.C{ci:03d}"
        try:
            if "split" in opts:
                texts = emit_cert.lean_files(D, ci, C, ns, chunk, int(opts.get("budget", 15000)))
            else:
                texts = {"": emit_cert.lean_file(D, ci, C, ns, chunk)}  # build first: a failure leaves no empty module
        except Exception as e:
            rec = dict(cls=ci, error=repr(e))
            print(json.dumps(rec), flush=True)
            log.write(json.dumps(rec) + "\n"); log.flush()
            continue
        sub = f"{outdir}/C{ci:03d}"
        if os.path.isdir(sub):
            for f in os.listdir(sub):
                os.remove(os.path.join(sub, f))
        for suf, text in texts.items():
            if suf:
                os.makedirs(sub, exist_ok=True)
            open(path if not suf else f"{sub}/{suf}.lean", "w").write(text)
        nodes = [c["nodes"] for c in C["cells"]]
        rec = dict(cls=ci, sides=len(C["P"]), chain=len(C["Bs"]), cells=len(nodes),
                   nodes=sum(nodes), max_nodes=max(nodes), subtrees=sum(c["npre"] for c in C["cells"]), secs=round(time.time() - t0, 1),
                   bytes=sum(len(t) for t in texts.values()), modules=len(texts))
        print(json.dumps(rec), flush=True)
        log.write(json.dumps(rec) + "\n"); log.flush()
    mods = sorted(f[:-5] for f in os.listdir(outdir) if f.endswith(".lean"))
    open(f"lean/ReflectZphi/Data/Cert{D}.lean", "w").write(
        f"/-! Reflectivity certificates, field key {D} (generated by tools/cert_all.py). -/\n"
        + "".join(f"import ReflectZphi.Data.Cert{D}.{m}\n" for m in mods))
    open(f"lean/scripts/CertAxioms{D}.lean", "w").write(
        f"import ReflectZphi.Data.Cert{D}\n\n"
        + "".join(f"#print axioms ReflectZphi.Data.Cert{D}.{m}.reflective\n" for m in mods))


if __name__ == "__main__":
    main()
